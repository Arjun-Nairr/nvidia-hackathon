def _desc():
    roles = list(core.ROLES)
    per_role = []
    for name in roles:
        g = core.ROLES[name]
        tools = "; ".join(f"{k} ({v['what']})" for k, v in g["eligible_tools"].items())
        must = g["mandatory_tools"]
        optional = [k for k in g["eligible_tools"] if k not in must]
        per_role.append(f"ROLE {name}: {g['creation_guidance']} Eligible tools: {tools}. The backend ALWAYS grants the foundation tools {', '.join(must)} "
                        f"(the specialist needs them to read its context, load its skills and keep its memory), so you do not need to request them; "
                        f"optional eligible tools you may add: {', '.join(optional) or 'none at present'}. "
                        f"Tool dependencies (a selection missing a prerequisite is refused with tool_dependency): "
                        + "; ".join(f"{k} needs {', '.join(v)}" for k, v in g["requires"].items()) + f". "
                        f"Capabilities that are NOT connected yet: {', '.join(g['not_connected'])}.")
    return ("Create a persistent, independently chatable specialist agent (its own Hermes profile, memory, skills and "
            "conversation) for the company. The backend REFUSES creation until the company context has the required details "
            f"({', '.join(core.COMPANY_LABELS[f] for f in core.REQUIRED_FIELDS)}); check read_company_context first and ask the user for "
            "what is missing. You GENERATE the company-specific objective and instructions from the company context - no placeholders, no invented "
            "facts. Custom skills are OPTIONAL (omit `skills` or send [] when the baseline skill plus your instructions are enough; at most "
            f"{core.MAX_SKILLS} reusable procedures otherwise). At most ONE specialist per role exists for this business: if the role already exists "
            "the backend answers role_exists with its agent_id and creates nothing; then tell the user to open that specialist's chat and use "
            "Customize mode to change it, and never try another name. "
            f" Supported roles: {', '.join(roles)}; use the role the user asked for and never request "
            "tools of another role. " + " ".join(per_role) + " "
            "The application grants access; requesting more than the role allows returns a corrective error. "
            "Creation does not start any task. Returns agent_id, conversation_id, granted_tools, approval_requirements, state.")


