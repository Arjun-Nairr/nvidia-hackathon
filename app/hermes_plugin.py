NOT_ALLOWED = ("create_agent is not permitted for this request: the backend classified it as {o}, which does not allow creating agents. "
               "Do not create an agent. Tell the user what you can do instead (answer from company context, or ask them to confirm they want a "
               "specialist (market analysis or social media) created).")


WRONG_ROLE = ("create_agent is not permitted for role {r!r} in this request: the backend classified it as {o} (role {w}). Create only that role, "
              "or ask the user to confirm which specialist they want.")


def _block_create_unless_allowed(tool_name=None, args=None, **kw):
    if tool_name != "create_agent":
        return None
    role = args.get("role") if isinstance(args, dict) else None
    if not turn_state.create_allowed():
        return {"action": "block", "message": NOT_ALLOWED.format(o=(turn_state.route or {}).get("outcome", "no routing decision"))}
    if isinstance(role, str) and not turn_state.create_allowed(role):
        rt = turn_state.route or {}
        return {"action": "block", "message": WRONG_ROLE.format(r=role, o=rt.get("outcome"), w=rt.get("role"))}
    return None


def _guarded_create(p, **kw):   # second layer: even if the hook were bypassed, the tool itself refuses
    if not turn_state.create_allowed():
        return json.dumps(core.err("not_permitted_for_request", NOT_ALLOWED.format(o=(turn_state.route or {}).get("outcome", "no routing decision")),
                                   hint="Only a request routed to a specialist-creation outcome may create an agent."))
    role = p.get("role") if isinstance(p, dict) else None
    if isinstance(role, str) and not turn_state.create_allowed(role):
        rt = turn_state.route or {}
        return json.dumps(core.err("role_not_permitted_for_request", WRONG_ROLE.format(r=role, o=rt.get("outcome"), w=rt.get("role")), "role"))
    return json.dumps(core.create_agent(p))


def _guarded_update(p, **kw):   # main only, and only for a request the backend routed to main
    if turn_state.route is None:
        return json.dumps(core.err("not_permitted_for_request", "update_company is only available while answering a routed user request."))
    return json.dumps(core.update_company(p if isinstance(p, dict) else {}, source="main"))


def _routing_context(**kw):
    c = (turn_state.route or {}).get("context")
    return {"context": c} if c else None


def register(ctx):
    from app import timing
    timing.register_hooks(ctx)  # no-op unless ECOM_TIMING=1
    me = os.environ.get("ECOM_AGENT_ID", "main")
    ctx.register_tool(name="read_company_context", toolset="ecom_company", schema=CONTEXT_SCHEMA,
                      handler=lambda p, **kw: json.dumps(core.read_company_context(p.get("section"), me)))
    if me != "main":   # specialists only; it is exposed to the model only when granted (toolset ecom_images)
        ctx.register_tool(name="inspect_image", toolset="ecom_images", schema=IMAGE_SCHEMA, handler=_inspect_image)
        ctx.register_tool(name="read_catalogue", toolset="ecom_catalogue", schema=CATALOGUE_SCHEMA, handler=_read_catalogue)
        ctx.register_tool(name="read_recorded_evidence", toolset="ecom_evidence", schema=EVIDENCE_SCHEMA, handler=_read_evidence)
        ctx.register_tool(name="save_listing_draft", toolset="ecom_drafts", schema=DRAFT_SCHEMA, handler=_save_draft)
        for schema, ts, fn in ((MP_LOCATE_SCHEMA, "ecom_mp_locate", research.locate), (MP_SEARCH_SCHEMA, "ecom_mp_search", research.search),
                               (MP_ITEM_SCHEMA, "ecom_mp_item", research.item), (MP_PHOTO_SCHEMA, "ecom_mp_photo", research.photo)):
            ctx.register_tool(name=schema["name"], toolset=ts, schema=schema, handler=_mp(fn))
        for schema, ts, fn in ((FB_ADV_SCHEMA, "ecom_fb_advertiser", ads.find_advertiser), (FB_SEARCH_SCHEMA, "ecom_fb_search", ads.search),
                               (FB_DETAIL_SCHEMA, "ecom_fb_detail", ads.detail), (FB_IMAGE_SCHEMA, "ecom_fb_image", ads.image),
                               (FB_SAVE_SCHEMA, "ecom_fb_save", ads.save_package), (FB_READ_SCHEMA, "ecom_fb_read", ads.read_package),
                               (FLYER_GEN_SCHEMA, "ecom_flyer_generate", flyer.generate), (FLYER_READ_SCHEMA, "ecom_flyer_read", flyer.read_flyer)):
            ctx.register_tool(name=schema["name"], toolset=ts, schema=schema, handler=_mp(fn))
    if me == "main":
        ctx.register_tool(name="create_agent", toolset="ecom_agents", schema=CREATE_SCHEMA,
                          handler=_guarded_create)
        ctx.register_tool(name="update_company", toolset="ecom_agents", schema=UPDATE_SCHEMA, handler=_guarded_update)
        ctx.register_hook("pre_tool_call", _block_create_unless_allowed)   # Hermes' supported veto point (block + message becomes the tool result)
        ctx.register_hook("pre_llm_call", _routing_context)               # trusted classification context appended to the user message
