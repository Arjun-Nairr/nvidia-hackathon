SKILLS_OWNED = ("skill_manage is refused: {names} is managed by the platform (the role's baseline skill, or a custom skill the operator manages). It can be read with skill_view, but only the "
                "operator can change it, in Customize mode through customize_specialist. Nothing in this call was applied. You may create and maintain your own other skills with skill_manage.")


def _win_name(seg):
    """One path segment as the OS sees it: Windows drops trailing dots and spaces ('skill.' IS the folder 'skill') and compares case-insensitively; '' when nothing real is left."""
    return seg.strip().rstrip(". ").lower()


def _skill_targets(args):
    """Every skill name a skill_manage call would touch (name, absorbed_into, category and every file_path segment, in their Windows-equivalent form) -> (names, unsafe); unsafe=True when the
    call's shape cannot be read safely (non-list operations, non-string fields, '..', absolute or drive paths, segments with nothing real left)."""
    a = args if isinstance(args, dict) else {}
    ops = a.get("operations")
    if ops is not None and (not isinstance(ops, list) or any(not isinstance(o, dict) for o in ops)):
        return set(), True
    rows = [{**a, **o} for o in ops] if ops else [a]   # a flat call, or each op with the outer name as its default
    names, unsafe = set(), False

    def add(value, path=False):
        nonlocal unsafe
        if not isinstance(value, str):
            unsafe = True
            return
        if path and (value.startswith(("/", "\\")) or (len(value) > 1 and value[1] == ":")):
            unsafe = True
        for seg in (x for x in re.split(r"[\\/]+", value) if x.strip()):
            n = _win_name(seg)
            if not n or (path and seg.strip() == ".."):
                unsafe = True
            else:
                names.add(n)
    for o in rows:
        add(o.get("name"))
        for key in ("absorbed_into", "category", "file_path"):
            if o.get(key) is not None:
                add(o[key], path=(key == "file_path"))
    return names, unsafe


def _skill_guard(agent_id, args):
    """Native skill_manage ownership: the role's baseline skill and the registry-managed custom skills change only through customize_specialist (never natively, not even in Customize mode);
    the agent's own other skills stay free. The WHOLE call is refused when any of its operations touches a protected skill, so a mixed batch applies nothing."""
    with core.db() as d:
        r = d.execute("SELECT role, skills FROM agents WHERE agent_id=?", (agent_id,)).fetchone()
    if not r:
        return None
    protected = {_win_name(roles.FOUNDATIONS[r["role"]]["baseline_name"]), *(_win_name(x["name"]) for x in json.loads(r["skills"]))}
    names, unsafe = _skill_targets(args)
    hit = sorted(names & protected)
    if hit:
        return SKILLS_OWNED.format(names=", ".join(hit))
    if unsafe:
        return SKILLS_OWNED.format(names="this skill_manage call (its shape cannot be checked against the managed skills)")
    return None


def _specialist_gate(tool_name=None, args=None, **kw):   # Hermes' veto point for specialists: no customization without the operator's flag, no tool the registry does not grant
    if tool_name == "customize_specialist" and not turn_state.customize:
        return {"action": "block", "message": CUSTOMIZE_DENIED}
    if tool_name in _ECOM_TOOLS and not core.is_granted(os.environ.get("ECOM_AGENT_ID", ""), tool_name):
        return {"action": "block", "message": _not_granted(tool_name)["error"]}
    if tool_name == "skill_manage" and (msg := _skill_guard(os.environ.get("ECOM_AGENT_ID", ""), args)):
        return {"action": "block", "message": msg}
    return None


