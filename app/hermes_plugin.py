def _inspect_image(p, **kw):
    r = core.prepare_image((p or {}).get("image_id") if isinstance(p, dict) else None)
    if not r["ok"]:
        return json.dumps(r)
    delivery = turn_state.image_delivery()   # preparation is not delivery: how Hermes will actually send this image for the active provider/model
    try:   # trusted inspection log (backend-written; a saved draft may only cite images inspected here). Logging trouble must not hide the image.
        listing.record_inspection(os.environ.get("ECOM_AGENT_ID", "main"), r, delivery)
    except Exception:
        pass
    note = (f"Image {r['image_id']} ({r['width']}x{r['height']}, {r['format']}) is attached below: these are its real pixels. Describe only what is "
            "visible, citing this image_id. List readable text exactly. Say what you are unsure of. Do not state fabric composition, quality, "
            "authenticity or sales performance unless text in the image says so; label such points unverified.")
    return {"_multimodal": True,
            "content": [{"type": "text", "text": note}, {"type": "image_url", "image_url": {"url": r["data_url"]}}],
            # used when pixels cannot travel (provider/model not declared vision-capable) and in saved history: must never claim the model saw it
            "text_summary": (f"[inspect_image {r['image_id']} ({r['width']}x{r['height']}): pixels are not visible in this message. If you cannot see "
                             "the image, say it could not be inspected; never describe an image you cannot see and do not submit image_observations for it.]"),
            "meta": {"image_id": r["image_id"], "width": r["width"], "height": r["height"], "sha256": r["sha256"]}}


